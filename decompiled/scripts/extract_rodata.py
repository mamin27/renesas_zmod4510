#!/usr/bin/env python3
"""Extract .rodata tables from objects of lib/lib_no2_o3.a into C source.

Usage: extract_rodata.py <objdir> <outdir>
<objdir> holds the objects unpacked with `ar x lib/lib_no2_o3.a`.
Writes <outdir>/no2_o3_data.c and <outdir>/no2_o3_nnet_data.c.
Floats are written as C99 hex literals, so the values are bit-exact.
"""
import struct
import subprocess
import sys

objdir, outdir = sys.argv[1], sys.argv[2]


def section(obj, name):
    out = "%s/%s.%s.bin" % (outdir, obj, name.strip("."))
    subprocess.check_call(["aarch64-linux-gnu-objcopy", "-O", "binary", "-j",
                           name, "%s/%s.c.o" % (objdir, obj), out])
    with open(out, "rb") as f:
        return f.read()


def floats(b, off, n):
    return struct.unpack("<%df" % n, b[off:off + 4 * n])


def fl(v):
    return float(v).hex() + "f" if v != 0 else "0.0f"


def farr(name, vals, per=4):
    lines = []
    for i in range(0, len(vals), per):
        lines.append("    " + ", ".join(fl(v) for v in vals[i:i + per]) + ",")
    return "const float %s[%d] = {\n%s\n};\n\n" % (name, len(vals), "\n".join(lines))


def u16arr(name, vals):
    return "const int16_t %s[%d] = {%s};\n" % (name, len(vals),
                                                ", ".join(str(v) for v in vals))


HDR = ("/* Generated by decompiled/scripts/extract_rodata.py from lib_no2_o3.a.\n"
       " * Do not edit by hand. */\n#include <stdint.h>\n#include \"no2_o3_data.h\"\n\n")

# --- no2_o3.c.o rodata ---
rod = section("no2_o3", ".rodata")
out = HDR
for name, off in [("no2_o3_longtermvar_start", 0), ("no2_o3_p_11", 0x10),
                  ("no2_o3_p_01", 0x20), ("no2_o3_p_02", 0x30),
                  ("no2_o3_p_10", 0x40), ("no2_o3_p_20", 0x50)]:
    out += farr(name, floats(rod, off, 4))
for name, off, n in [("no2_o3_epa_o3_1h_aqi", 0x60, 6), ("no2_o3_epa_o3_1h_conc", 0x70, 6),
                     ("no2_o3_epa_no2_1h_aqi", 0x80, 6), ("no2_o3_epa_no2_1h_conc", 0x90, 6),
                     ("no2_o3_epa_o3_8h_aqi", 0xa0, 5), ("no2_o3_epa_o3_8h_conc", 0xb0, 5)]:
    out += u16arr(name, struct.unpack("<%dh" % n, rod[off:off + 2 * n]))
with open(outdir + "/no2_o3_data.c", "w") as f:
    f.write(out)

# --- NN weights: layer offsets and sizes (floats) taken from the object symbols ---
LAYERS = [(0, 300), (0x4b0, 315), (0x9a0, 160), (0xc20, 55), (0xd00, 18), (0xd50, 4)]
out = HDR
for net in ("NO2", "O3"):
    r = section("no2_o3_%s_nnet" % net, ".rodata")
    assert len(r) == 0xd60, len(r)
    for i, (off, n) in enumerate(LAYERS):
        out += farr("no2_o3_%s_nnet_layer%d" % (net, 2 * i), floats(r, off, n))
with open(outdir + "/no2_o3_nnet_data.c", "w") as f:
    f.write(out)
print("ok")
